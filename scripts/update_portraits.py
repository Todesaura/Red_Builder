"""Refresh the static portrait catalogue and lightweight gallery previews."""
from pathlib import Path
import json,re
from PIL import Image,ImageOps
root=Path(__file__).resolve().parents[1]
folder=root/'data/portraits'
thumbs=folder/'thumbnails'
thumbs.mkdir(exist_ok=True)
entries=[]
for path in sorted(folder.glob('*.png')):
 match=re.fullmatch(r'([A-Za-z]+)-([MW])-(\d+)\.png',path.name)
 if not match: continue
 role,gender,number=match.groups()
 thumb=thumbs/(path.stem+'.jpg')
 with Image.open(path) as img:
  ImageOps.fit(img.convert('RGB'),(180,220),method=Image.Resampling.LANCZOS).save(thumb,quality=82,optimize=True)
 entries.append(dict(id=path.stem,role=role.lower(),gender=gender,number=int(number),src='data/portraits/'+path.name,thumbnail='data/portraits/thumbnails/'+thumb.name))
entries.sort(key=lambda p:(p['role'],p['gender'],p['number']))
(root/'js/portrait-catalog.js').write_text('// Generated by scripts/update_portraits.py; keep original files in data/portraits.\nexport const PORTRAITS = '+json.dumps(entries,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
print(f'{len(entries)} portraits and previews generated.')
